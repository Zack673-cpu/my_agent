def build_prompt(scene_key: str | None = None) -> str:
    """返回可直接使用的提示词。

    Args:
        scene_key: 场景标识（``SCENE_PRESETS`` 的键）。为 ``None`` 或未知
            时返回基础模板本身（保留 ``<...>`` 占位，供用户手动补充）。

    Returns:
        拼好的完整提示词字符串。
    """
    preset = SCENE_PRESETS.get(scene_key or "")
    if not preset:
        return COMMON_TEMPLATE
    # 用场景姿态片段替换基础模板中的占位说明。
    placeholder_start = "【人物姿态与动作】<"
    prefix, sep, rest = COMMON_TEMPLATE.partition(placeholder_start)
    if not sep:
        return COMMON_TEMPLATE
    # rest 形如 "...占位内容...>\n\n【光影融合】..."，去掉占位到 ">" 为止。
    _, gt, tail = rest.partition(">")
    if not gt:
        return COMMON_TEMPLATE
    return f"{prefix}【人物姿态与动作】{preset['pose']}{tail}"


